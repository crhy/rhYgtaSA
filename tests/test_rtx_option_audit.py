#!/usr/bin/env python3
"""n16 gate: the second key audit, and the tonemap block it guards.

Two things are checked here.

1. tools/rtx-option-audit.py against config/rtx-options-1.6.1.tsv - the runtime's OWN option
   table (RtxOptions.md, auto-generated by Remix at the remix-1.6.1 tag; the name column is
   RtxOptionImpl::getFullName() = category + "." + name, rtx_option.h:267). This is the audit
   tools/rtxkeycheck.py cannot be: a `strings` grep accepts rtx.<category>.<leaf> whenever both
   halves appear anywhere in .trex/d3d9.dll, and the n16 task file's key
   `rtx.tonemap.tonemappingMode` is exactly such a name - it does not exist, the option is
   `rtx.tonemappingMode` (rtx_options.h:1181), and a key that names no option is kept in the file
   and ignored (rtx_option_layer.cpp:416-421). So the audit is run on the profiles, and the fake
   name is asserted to still be rejected so the check cannot go vacuous.

2. the n16 block itself: config/rtx.conf, config/rtx.conf.perf and config/rtx.conf.nopops all
   carry the same tonemap values, so switching profile cannot silently change the grade, and the
   runtime defaults those values are measured against are still the defaults (if NVIDIA moves a
   default, the -0.5 EV anchor's meaning changes and we want to hear about it).
"""
import os
import re
import subprocess
import sys
import unittest

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "tools"))

TABLE = os.path.join(REPO, "config", "rtx-options-1.6.1.tsv")
DEAD = os.path.join(REPO, "config", "rtx-dead-keys.txt")
CONF = os.path.join(REPO, "config", "rtx.conf")
PERF = os.path.join(REPO, "config", "rtx.conf.perf")
NOP = os.path.join(REPO, "config", "rtx.conf.nopops")

KEYRE = re.compile(r"^\s*(rtx\.[A-Za-z0-9_.]+)\s*=\s*(.*)$")

# what n16 ships, in every profile (docs/TARGET.md §4 T4)
N16 = {
    "rtx.tonemappingMode": "0",                 # 0 = Global (runtime default 1 = Local)
    "rtx.tonemap.exposureBias": "-0.5",         # EV anchor, auto exposure is off
    "rtx.localtonemap.shadows": "1.0",          # was 2.5 in this repo (runtime default 2)
    "rtx.localtonemap.highlights": "2.0",       # runtime default 4, never set before n16
    "rtx.tonemap.finalizeWithACES": "True",     # kept (runtime default False)
}

# names that read like real options and are not - the negative controls
FAKE = [
    "rtx.tonemap.tonemappingMode",      # the n16 task file's spelling
    "rtx.userBrightness",               # really rtx.userBrightness.userBrightness
    "rtx.userBrightnessEVRange",        # really rtx.userBrightnessEVRange.userBrightnessEVRange
    "rtx.antiCulling.object",           # really rtx.antiCulling.object.enable
    "rtx.enableFogMaxDistanceRemap",    # really rtx.volumetrics.enableFogMaxDistanceRemap
    "rtx.tonemap.toneCurveMaxStop",     # a plausible typo
]


def parse(path):
    out = {}
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            m = KEYRE.match(line)
            if m:
                out[m.group(1)] = m.group(2).strip()
    return out


def table():
    opts = {}
    with open(TABLE, encoding="utf-8") as f:
        for line in f:
            if line.startswith("#"):
                continue
            p = line.rstrip("\n").split("\t")
            if len(p) >= 5:
                opts[p[0]] = {"type": p[1], "default": p[2], "min": p[3], "max": p[4]}
    return opts


def audit(files, allow_dead=True):
    cmd = [sys.executable, os.path.join("tools", "rtx-option-audit.py"), "--quiet"]
    if not allow_dead:
        cmd.append("--allow-dead")
        cmd.append("")
    return subprocess.run(cmd + files, cwd=REPO, capture_output=True, text=True)


class TestOptionTable(unittest.TestCase):
    def setUp(self):
        self.opts = table()

    def test_the_table_is_the_runtime_table(self):
        self.assertGreater(len(self.opts), 1000,
                           "config/rtx-options-1.6.1.tsv looks truncated - rebuild it with "
                           "tools/rtx-option-audit.py --make-from-md")
        # a handful of names we know this runtime has, with the defaults n16 reasons from
        for key, default in (("rtx.tonemappingMode", "1"),
                             ("rtx.localtonemap.shadows", "2"),
                             ("rtx.localtonemap.highlights", "4"),
                             ("rtx.localtonemap.exposure", "0.75"),
                             ("rtx.tonemap.finalizeWithACES", "False"),
                             ("rtx.localtonemap.finalizeWithACES", "True"),
                             ("rtx.useLegacyACES", "True"),
                             ("rtx.tonemap.exposureBias", "0"),
                             ("rtx.userBrightness.userBrightness", "50"),
                             ("rtx.userBrightnessEVRange.userBrightnessEVRange", "3"),
                             ("rtx.postfx.exposureFraction", "0.4")):
            self.assertIn(key, self.opts, "%s is not in the 1.6.1 table" % key)
            self.assertEqual(self.opts[key]["default"], default,
                             "%s default moved from %s - the n16 reasoning cites it"
                             % (key, default))

    def test_the_task_files_names_are_not_options(self):
        for key in FAKE:
            self.assertNotIn(key, self.opts, "%s is suddenly an option: table refreshed?" % key)

    def test_the_strings_audit_still_accepts_the_fake_name(self):
        """Why this file exists: rtxkeycheck.py cannot tell these apart."""
        from rtxkeycheck import load_keys, verdict
        dotted, leaves = load_keys(os.path.join(REPO, "config", "rtx-runtime-keys.txt"))
        self.assertIsNotNone(verdict("rtx.tonemap.tonemappingMode", dotted, leaves)[0],
                             "rtxkeycheck changed - re-check whether the second audit is needed")

    def test_profiles_only_carry_options_or_documented_dead_keys(self):
        r = audit(["config/rtx.conf", "config/rtx.conf.perf", "config/rtx.conf.nopops"])
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)

    def test_without_the_allow_list_the_dead_keys_are_still_flagged(self):
        r = audit(["config/rtx.conf.perf"], allow_dead=False)
        self.assertNotEqual(r.returncode, 0)
        for key in ("rtx.enableFogMaxDistanceRemap", "rtx.antiCulling.object",
                    "rtx.antiCulling.light"):
            self.assertIn(key, r.stdout, "%s no longer flagged - fix the list" % key)

    def test_the_audit_rejects_the_fake_names(self):
        tmp = os.path.join(REPO, "build", "tmp", "n16-fake-keys.conf")
        os.makedirs(os.path.dirname(tmp), exist_ok=True)
        with open(tmp, "w", encoding="utf-8") as f:
            for key in FAKE:
                f.write("%s = 0\n" % key)
        r = audit(["build/tmp/n16-fake-keys.conf"], allow_dead=False)
        self.assertNotEqual(r.returncode, 0, "the option-table audit accepted a fake name")
        for key in FAKE:
            self.assertIn(key, r.stdout)

    def test_dead_key_list_is_short_and_still_dead(self):
        dead = [l.split("\t")[0] for l in open(DEAD, encoding="utf-8")
                if not l.startswith("#") and l.strip()]
        self.assertEqual(len(dead), 5, "the dead-key allow-list grew or shrank: %s" % dead)
        for key in dead:
            self.assertNotIn(key, self.opts,
                             "%s is a real option now - delete it from %s" % (key, DEAD))


class TestN16Block(unittest.TestCase):
    def test_every_profile_ships_the_same_tonemap(self):
        for path in (CONF, PERF, NOP):
            got = parse(path)
            for key, want in N16.items():
                self.assertEqual(got.get(key), want,
                                 "%s: %s is %r, n16 ships %r"
                                 % (os.path.basename(path), key, got.get(key), want))

    def test_the_anchor_is_a_real_ev_not_a_default(self):
        """exposureBias is only an anchor because auto exposure is off in all three profiles."""
        for path in (CONF, PERF, NOP):
            self.assertEqual(parse(path).get("rtx.autoExposure.enabled"), "False",
                             "%s turned auto exposure on - the EV anchor is no longer a hard number"
                             % os.path.basename(path))

    def test_no_profile_writes_the_user_brightness_keys(self):
        """They are UserSetting keys: the Remix UI's Brightness slider, stored in user.conf, which
        sits above rtx.conf. A profile that writes them fights the player."""
        for path in (CONF, PERF, NOP):
            for key in ("rtx.userBrightness.userBrightness",
                        "rtx.userBrightnessEVRange.userBrightnessEVRange"):
                self.assertNotIn(key, parse(path),
                                 "%s writes %s - that belongs to the user layer"
                                 % (os.path.basename(path), key))

    def test_the_motion_blur_key_is_not_used_as_an_exposure(self):
        for path in (CONF, PERF, NOP):
            self.assertNotIn("rtx.postfx.exposureFraction", parse(path),
                             "%s sets the motion-blur shutter fraction; it is not an exposure knob"
                             % os.path.basename(path))


if __name__ == "__main__":
    unittest.main(verbosity=2)
