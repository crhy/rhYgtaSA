#!/usr/bin/env python3
"""Audit rtx.conf-style keys against the runtime's OWN option table (name + default).

    tools/rtx-option-audit.py FILE [FILE ...]          audit keys (exit 1 on unknown)
    tools/rtx-option-audit.py --show KEY [KEY ...]     print type/default of a key
    tools/rtx-option-audit.py --make-from-md MD [-o TSV]   rebuild the table from RtxOptions.md

Keys listed in config/rtx-dead-keys.txt (one per line, key<TAB>reason) are reported as
"dead (allowed)" instead of failing the run: those are the keys our shipped profiles keep on
purpose, each with its reason written next to it. --allow-dead '' turns the list off.

Why this exists next to tools/rtxkeycheck.py (n16, 2026-11-13): rtxkeycheck.py greps the
runtime binary's *strings*, so it accepts any "rtx.<category>.<leaf>" whose category and leaf
both appear somewhere in .trex/d3d9.dll. For nested keys that is not a name check at all -
`rtx.tonemap.tonemappingMode` (which does not exist) passes it as "leaf+category", while the real
key is `rtx.tonemappingMode`. A key that names no option is not an error to the runtime: it is
kept in the file and ignored (rtx_option_layer.cpp keeps "keys that no option manages"), which is
how a tuned setting does nothing for a week.

The table this tool checks against is the runtime's own: RtxOptions.md is auto-generated by Remix
itself (`DXVK_DOCUMENTATION_WRITE_RTX_OPTIONS_MD=1`, rtx_options.h:1368) and a unit test in the
runtime's repo fails if it drifts from the code (tests/rtx/unit/test_documentation.cpp). The name
column is `RtxOptionImpl::getFullName()` = category + "." + name (rtx_option.h:267), i.e. exactly
the string rtx.conf must carry. So this table answers the two questions rtxkeycheck cannot:
does an option with THIS EXACT name exist, and what does the runtime default it to?

Provenance of config/rtx-options-1.6.1.tsv (our runtime is 1.6.1, see deps/manifest.json):
    curl -sL -o RtxOptions.md \
      https://raw.githubusercontent.com/NVIDIAGameWorks/dxvk-remix/remix-1.6.1/RtxOptions.md
    python3 tools/rtx-option-audit.py --make-from-md RtxOptions.md
Upstream: https://github.com/NVIDIAGameWorks/dxvk-remix (MIT, same licence as the vendored
third_party/remix/remix_c.h). Re-point --make-from-md at a newer tag when the runtime updates;
the file name carries the version so a mismatch is visible.

Verdicts:
    ok            the exact name is in the table (plus: is our value the default or not)
    NOT AN OPTION the name is absent; the tool then lists the table's names with the same leaf,
                  which is how a renamed or re-categorised key gets found instead of guessed at
    unknown       absent and nothing shares its leaf
"""
import argparse
import os
import re
import sys

TABLE = "config/rtx-options-1.6.1.tsv"
DEAD = "config/rtx-dead-keys.txt"
KEYRE = re.compile(r"^\s*(rtx\.[A-Za-z0-9_.]+)\s*=\s*(.*?)\s*(?:#.*)?$")
ROWRE = re.compile(r"^\|([^|]+)\|([^|]*)\|([^|]*)\|([^|]*)\|([^|]*)\|(.*)\|$")


def load_table(path):
    opts = {}
    with open(path, "r", encoding="utf-8") as fh:
        for line in fh:
            if line.startswith("#") or not line.strip():
                continue
            parts = line.rstrip("\n").split("\t")
            if len(parts) < 5:
                continue
            name, typ, default, lo, hi = parts[:5]
            opts[name] = {"type": typ, "default": default, "min": lo, "max": hi,
                          "desc": parts[5] if len(parts) > 5 else ""}
    return opts


def make_table(md_path, out_path):
    """Parse the runtime's auto-generated RtxOptions.md into the vendored TSV."""
    rows = []
    with open(md_path, "r", encoding="utf-8") as fh:
        for line in fh:
            m = ROWRE.match(line.rstrip("\n"))
            if not m:
                continue
            name = m.group(1).strip()
            if not name.startswith("rtx."):          # the header row, and anything odd
                continue
            desc = m.group(6).strip().replace("\\.", ".").replace("\\n", " ")
            rows.append([name, m.group(2).strip(), m.group(3).strip(),
                         m.group(4).strip(), m.group(5).strip(), desc])
    if len(rows) < 500:
        sys.exit("%s: only %d option rows parsed - that is not the runtime's table"
                 % (md_path, len(rows)))
    rows.sort(key=lambda r: r[0])
    names = {r[0] for r in rows}
    with open(out_path, "w", encoding="utf-8") as out:
        out.write("# RTX Remix %s option table: name<TAB>type<TAB>default<TAB>min<TAB>max<TAB>description\n"
                  % os.path.basename(out_path).rsplit(".", 1)[0].split("-")[-1])
        out.write("# Generated by tools/rtx-option-audit.py --make-from-md from the runtime's own\n")
        out.write("# auto-generated RtxOptions.md (upstream NVIDIAGameWorks/dxvk-remix, MIT).\n")
        out.write("# %d options. Names are RtxOptionImpl::getFullName() = category + \".\" + name,\n" % len(rows))
        out.write("# i.e. exactly what rtx.conf must write. See the tool's docstring.\n")
        for r in rows:
            out.write("\t".join(x.replace("\t", " ") for x in r) + "\n")
    print("wrote %s: %d options" % (out_path, len(rows)))
    return 0


def suggest(name, opts):
    leaf = name.split(".")[-1]
    return sorted(k for k in opts if k.split(".")[-1] == leaf)


def load_dead(path):
    dead = {}
    if not path or not os.path.exists(path):
        return dead
    for line in open(path, "r", encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        key, _, why = line.rstrip("\n").partition("\t")
        dead[key.strip()] = why.strip()
    return dead


def check_file(path, opts, quiet, dead=None, deadfile=DEAD):
    bad = 0
    seen = 0
    for n, line in enumerate(open(path, "r", encoding="utf-8", errors="replace"), 1):
        m = KEYRE.match(line)
        if not m:
            continue
        key, val = m.group(1), m.group(2)
        seen += 1
        if key in opts:
            if not quiet:
                d = opts[key]
                same = "same as default" if val and val.strip() == d["default"] else \
                       "runtime default %s" % (d["default"] or "-")
                extra = ""
                if d["min"] or d["max"]:
                    extra = "  range [%s, %s]" % (d["min"] or "-", d["max"] or "-")
                print("ok    %-52s %-7s %s%s" % (key, d["type"], same, extra))
            continue
        if key in (dead or {}):
            if not quiet:
                print("dead  %-52s allowed by %s: %s"
                      % (key, os.path.basename(deadfile), (dead or {})[key][:150]))
            continue
        sibs = suggest(key, opts)
        if sibs:
            bad += 1
            print("FAIL  %s:%d %s  - not an option of this runtime; same leaf: %s"
                  % (path, n, key, ", ".join(sibs[:6])))
        else:
            bad += 1
            print("FAIL  %s:%d %s  - no option of this runtime has this leaf" % (path, n, key))
    print("%s: %d keys, %d not options" % (path, seen, bad))
    return bad


def main(argv=None):
    ap = argparse.ArgumentParser(description="Audit rtx.conf keys against the runtime's option table.")
    ap.add_argument("files", nargs="*")
    ap.add_argument("--table", default=TABLE)
    ap.add_argument("--allow-dead", default=DEAD, metavar="FILE",
                    help="keys to report but not fail on (default %s; '' disables)" % DEAD)
    ap.add_argument("--quiet", action="store_true")
    ap.add_argument("--show", nargs="+", metavar="KEY", help="print type/default/min/max for keys")
    ap.add_argument("--make-from-md", metavar="MD", help="rebuild the table from an RtxOptions.md")
    ap.add_argument("-o", "--out", default=TABLE)
    a = ap.parse_args(argv)

    if a.make_from_md:
        return make_table(a.make_from_md, a.out)

    if not os.path.exists(a.table):
        sys.exit("%s missing - rebuild it with --make-from-md (see the docstring)" % a.table)
    opts = load_table(a.table)

    dead = load_dead(a.allow_dead)
    if a.show:
        for k in a.show:
            d = opts.get(k)
            if d:
                print("%-52s %-8s default=%-8s range=[%s, %s]  %s"
                      % (k, d["type"], d["default"] or "-", d["min"] or "-", d["max"] or "-",
                         d.get("desc", "")))
            else:
                print("%-52s NOT AN OPTION in %s; same leaf: %s"
                      % (k, os.path.basename(a.table), ", ".join(suggest(k, opts)) or "none"))
        return 0

    if not a.files:
        ap.error("no files given")
    total = 0
    for f in a.files:
        total += check_file(f, opts, a.quiet, dead, a.allow_dead)
    if total:
        print("NOT OPTIONS: %d" % total)
        return 1
    print("every key names an option of this runtime")
    return 0


if __name__ == "__main__":
    sys.exit(main())
