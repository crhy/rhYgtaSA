#!/usr/bin/env python3
"""Build the vocabulary of rtx.conf option names this Remix runtime actually knows.

Usage:
    strings -a -n 4 <game>/.trex/d3d9.dll > build/tmp/s22/d3d9.strings.txt
    tools/rtx-runtime-keys.py build/tmp/s22/d3d9.strings.txt > config/rtx-runtime-keys.txt

The runtime keeps its option table in .rdata as "tooltip line(s)" followed by the option's
name, and writes/reads rtx.conf with the full "rtx.<category>.<name>" spelling. So two
vocabularies can be recovered from `strings`:

  dotted  every rtx.<...> sequence that appears anywhere (option paths, and the paths the
          tooltips quote, e.g. "rtx.texturemanager.fixedBudgetMiB")
  leaf    every bare identifier line within PROSE_WINDOW lines of prose - the option table
          interleaves tooltip and name ("...description...", "nearPlaneOverride",
          "pathMaxBounces"), so "directly follows" is not enough ("useSampleStealing",
          "budgetPercentageOfAvailableVram", ...)

tools/rtxkeycheck.py turns a config key into a verdict from these two sets. Regenerate this
whenever the runtime updates: a key that is in the file but not in the runtime is a typo, and
a key the runtime renamed is silently ignored by the renderer.
"""
import re
import sys

DOTTED = re.compile(r"rtx\.[A-Za-z0-9_]+(?:\.[A-Za-z0-9_]+)*")
NAME = re.compile(r"[a-z][A-Za-z0-9_]*(?:\.[A-Za-z0-9_]+)*")


PROSE_WINDOW = 4


def is_prose(line: str) -> bool:
    return " " in line and len(line) > 12 and bool(re.search(r"[a-z] [a-z]", line))


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    dotted, leaves = set(), set()
    with open(sys.argv[1], "r", errors="replace") as fh:
        recent = 0
        for line in fh:
            line = line.rstrip("\n")
            for m in DOTTED.findall(line):
                dotted.add(m)
            if " " not in line and NAME.fullmatch(line) and recent:
                leaves.add(line)
            recent = PROSE_WINDOW if is_prose(line) else (recent - 1 if recent else 0)
    print("# generated by tools/rtx-runtime-keys.py from `strings` on the Remix runtime")
    print("# (dotted option path | bare option name) - see the script docstring")
    for k in sorted(dotted):
        print("dotted\t" + k)
    for k in sorted(leaves):
        print("leaf\t" + k)
    print("# %d dotted, %d leaf" % (len(dotted), len(leaves)), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
