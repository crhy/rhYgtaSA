#!/usr/bin/env python3
"""s05 — make GTA SA's rear-view mirrors actually reflect under RTX Remix.

GTA SA paints its mirrors: the glass is a few triangles of the car body atomic sampling the shared
reflection stand-ins in models/generic/vehicle.txd (`xvehicleenv128`, `vehicleenvmap128`). Under
Remix every surface is path traced, so a mirror only needs a perfectly smooth metallic material —
Remix then reflects whatever is behind it. Replacement materials are keyed to the Remix *texture
hash* of the texture the game uploaded, as `over "RootNode" { over "Looks" { over "mat_<HASH>" } }`,
which is exactly how the GTASA-Remix pack does it (and the pack already uses that recipe for the
mirrors of its own re-authored taxi/police meshes: `def Material "Mirror"` in meshes/Vehicles.usda).

This tool writes <game>/rtx-remix/mods/gameReadyAssets/rhy_mirrors.usda (AperturePBR_Opacity,
metallic 1, roughness 0.02, albedo white, no normal/roughness/metallic texture) with one override
per hash in REPO/config/mirror-hashes.txt, and sublayers it into gameReadyAssets/mod.usda exactly
once. mod.usda is backed up to mod.usda.bak-rhy-mirrors on the first run (never overwritten);
`--remove` restores that backup and deletes the generated file.

usage:
  tools/mirrors.py [GAME_DIR] [--hash 0x1234ABCD5678EF90 ...] [--config FILE]
                   [--position first|last] [--dry-run] [--remove] [--print]

GAME_DIR defaults to /media/rhy/data/Gamez/GTASA-RTX. Hashes come from the config file and/or
--hash. The generated USD is validated (text USD header, balanced braces/brackets/parens, only
inputs that AperturePBR_Opacity.mdl declares) before anything is written.
"""
import argparse
import os
import re
import shutil
import sys

GAME_DEFAULT = "/media/rhy/data/Gamez/GTASA-RTX"
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONFIG_DEFAULT = os.path.join(REPO, "config", "mirror-hashes.txt")

LAYER = "rhy_mirrors.usda"
SUB = "@./%s@" % LAYER
BACKUP = "mod.usda.bak-rhy-mirrors"
HASH_RE = re.compile(r"0[xX]([0-9a-fA-F]{16})")

# inputs declared by gameReadyAssets/materials/AperturePBR_Opacity.mdl (Remix 1.6.1); the full list
# is what meshes/Rail Remaster/rail_base.usda writes for that mdl.
MDL_INPUTS = {
    "diffuse_color_constant", "diffuse_texture", "metallic_constant", "metallic_texture",
    "reflection_roughness_constant", "reflectionroughness_texture", "normalmap_texture",
    "opacity_constant", "encoding", "alpha_test_type", "alpha_test_reference_value",
    "blend_enabled", "blend_type", "inverted_blend", "use_legacy_alpha_state",
    "enable_emission", "emissive_color_constant", "emissive_mask_texture", "emissive_intensity",
    "enable_thin_film", "thin_film_thickness_constant", "thin_film_thickness_from_albedo_alpha",
    "sprite_sheet_fps", "sprite_sheet_cols", "sprite_sheet_rows",
    "height_texture", "displace_in", "anisotropy_constant", "anisotropy_texture",
    "exclude", "ignore_material",
}

BODY = '''#usda 1.0
# {layer} - generated by REPO/tools/mirrors.py. Do not edit by hand: edit
# REPO/config/mirror-hashes.txt (or pass --hash) and re-run the tool.
#
# GTA SA paints its rear-view mirrors. The glass is a few triangles inside the car body atomic that
# sample the shared reflection stand-ins of models/generic/vehicle.txd (xvehicleenv128: 128x128, 13
# colours, hard 3-band gradient; vehicleenvmap128: 128x128 sky->ground gradient). Under RTX Remix
# every surface is path traced, so those surfaces only need a perfectly smooth metal: Remix then
# reflects what is behind them. Same recipe the pack uses for its own taxi/police mirror meshes
# (`def Material "Mirror"` in meshes/Vehicles.usda: AperturePBR_Opacity, metallic 1, roughness 0).
# See REPO/docs/MIRRORS.md.
(
    customLayerData = {{
        dictionary omni_layer = {{
            dictionary locked = {{
            }}
            dictionary muteness = {{
            }}
        }}
    }}
    upAxis = "Z"
)

over "RootNode"
{{
    over "Looks"
    {{
{blocks}    }}
}}
'''

BLOCK = '''        over "mat_{hash}"{comment}
        {{
            over "Shader"
            {{
                uniform asset info:mdl:sourceAsset = @./materials/AperturePBR_Opacity.mdl@
                uniform token info:mdl:sourceAsset:subIdentifier = "AperturePBR_Opacity"
                color3f inputs:diffuse_color_constant = (1, 1, 1)
                float inputs:metallic_constant = 1
                float inputs:reflection_roughness_constant = {roughness}
                asset inputs:diffuse_texture = @@
                asset inputs:metallic_texture = @@
                asset inputs:reflectionroughness_texture = @@
                asset inputs:normalmap_texture = @@
            }}
        }}

'''


def bracket_scan(text):
    """The bare bracket stream of `text`, skipping # comments, "strings" and @asset@ paths."""
    out, i, n = [], 0, len(text)
    while i < n:
        c = text[i]
        if c == "#":
            while i < n and text[i] != "\n":
                i += 1
        elif text.startswith('"""', i):
            i += 3
            while i < n and not text.startswith('"""', i):
                i += 1
            i += 3
        elif c == '"':
            i += 1
            while i < n and text[i] != '"':
                i += 2 if text[i] == "\\" else 1
            i += 1
        elif c == "@":
            j = text.find("@", i + 1)
            if j < 0:
                return ["<unterminated @asset@>"]
            i = j + 1
        elif c in "{}()[]":
            out.append(c)
            i += 1
        else:
            i += 1
    return out


def validate(text, what, need_mat=False):
    """Raise ValueError unless `text` is sane text USD for Remix."""
    if not text.startswith("#usda 1.0\n"):
        raise ValueError("%s: first line must be '#usda 1.0'" % what)
    stream = bracket_scan(text)
    pairs = {")": "(", "]": "[", "}": "{"}
    stack = []
    for b in stream:
        if b in "([{":
            stack.append(b)
        elif b in ")]}":
            if not stack or stack[-1] != pairs[b]:
                raise ValueError("%s: unbalanced bracket %r (stream: %s...)" %
                                 (what, b, "".join(stack[-6:])))
            stack.pop()
    if stack:
        raise ValueError("%s: unclosed bracket(s) %s" % (what, "".join(stack)))
    for line in text.splitlines():
        m = re.match(r"\s*[A-Za-z0-9_]+\s+inputs:([A-Za-z0-9_]+)\s*=", line)
        if m and m.group(1) not in MDL_INPUTS:
            raise ValueError("%s: input %r is not declared by AperturePBR_Opacity.mdl" %
                             (what, m.group(1)))
    if need_mat and "mat_" not in text:
        raise ValueError("%s: no mat_<hash> override, nothing for Remix to apply" % what)


def read_hashes(path, extra):
    """[(HASH, label)] from the config file plus --hash values; comments and blanks ignored."""
    out, seen = [], set()
    if path and os.path.exists(path):
        for lineno, raw in enumerate(open(path, encoding="utf-8"), 1):
            line = raw.split("#", 1)
            comment = line[1].strip() if len(line) > 1 else ""
            m = HASH_RE.search(line[0])
            if not m:
                continue
            h = m.group(1).upper()
            if h in seen:
                print("  note: %s:%d duplicates %s" % (path, lineno, h))
                continue
            seen.add(h)
            out.append((h, comment or "from config"))
    elif path:
        print("note: no config at %s" % path)
    for h in extra:
        m = HASH_RE.fullmatch(h.strip()) or HASH_RE.search(h)
        if not m:
            raise SystemExit("--hash %r is not 0x + 16 hex digits" % h)
        h = m.group(1).upper()
        if h not in seen:
            seen.add(h)
            out.append((h, "from --hash"))
    return out


def render(entries, roughness):
    blocks = []
    for h, label in entries:
        comment = "   # %s" % label if label else ""
        blocks.append(BLOCK.format(hash=h, comment=comment, roughness=roughness))
    return BODY.format(layer=LAYER, blocks="".join(blocks))


def patch_mod_usda(text, position):
    """Insert SUB into mod.usda's subLayers. Returns (new_text, changed, why)."""
    if SUB in bracket_free(text):
        return text, False, "sublayer already present"
    m = re.search(r"(\n(\s*)subLayers\s*=\s*\[)(.*?)(\])", text, re.S)
    if not m:
        raise ValueError("mod.usda has no subLayers = [ ... ] block; refusing to guess where to "
                         "put the mirror layer")
    head, indent, items, tail = m.group(1), m.group(2), m.group(3), m.group(4)
    entry = "\n%s    @./%s@" % (indent, LAYER)
    if position == "first":
        new_items = entry + "," + items
    else:
        stripped = items.rstrip()
        trail = items[len(stripped):]
        comma = "" if stripped.endswith(",") else ","
        new_items = stripped + comma + entry + trail
    return text[:m.start()] + head + new_items + tail + text[m.end():], True, "sublayer added (%s)" % position


def bracket_free(text):
    """mod.usda with comments stripped, for a reliable 'is it already there' test."""
    return "\n".join(line.split("#", 1)[0] for line in text.splitlines())


def main():
    ap = argparse.ArgumentParser(add_help=True, description=__doc__.splitlines()[0])
    ap.add_argument("game", nargs="?", default=GAME_DEFAULT, help="game folder (default %s)" % GAME_DEFAULT)
    ap.add_argument("--hash", action="append", default=[], help="texture hash, repeatable")
    ap.add_argument("--config", default=CONFIG_DEFAULT, help="hash list (default config/mirror-hashes.txt)")
    ap.add_argument("--roughness", default="0.02", help="reflection_roughness_constant (default 0.02)")
    ap.add_argument("--position", choices=["first", "last"], default="first",
                    help="where in mod.usda subLayers (USD composes strongest-first, so 'first' "
                         "beats the pack's SARemix vehicle materials)")
    ap.add_argument("--remove", action="store_true", help="undo: restore mod.usda, delete the layer")
    ap.add_argument("--dry-run", action="store_true", help="print what would change, write nothing")
    ap.add_argument("--print", action="store_true", dest="show", help="print the generated USD")
    args = ap.parse_args()

    assets = os.path.join(args.game, "rtx-remix", "mods", "gameReadyAssets")
    mod = os.path.join(assets, "mod.usda")
    layer = os.path.join(assets, LAYER)
    bak = os.path.join(assets, BACKUP)
    if not os.path.isdir(assets):
        raise SystemExit("no %s - is %s the game folder?" % (assets, args.game))
    if not os.path.isfile(mod):
        raise SystemExit("no %s - the Remix pack is not installed there" % mod)
    mdl = os.path.join(assets, "materials", "AperturePBR_Opacity.mdl")
    if not os.path.isfile(mdl):
        print("warning: %s missing; the generated layer points at it anyway" % mdl)

    if args.remove:
        removed = []
        if os.path.isfile(layer):
            removed.append(layer)
            if not args.dry_run:
                os.remove(layer)
        if os.path.isfile(bak):
            if not args.dry_run:
                shutil.copyfile(bak, mod)
            removed.append("%s (restored over mod.usda)" % bak)
        else:
            text = open(mod, encoding="utf-8").read()
            new, changed, why = strip_sublayer(text)
            if changed:
                validate(new, "mod.usda")
                if not args.dry_run:
                    open(mod, "w", encoding="utf-8").write(new)
                removed.append("mod.usda: %s" % why)
        if not removed:
            print("nothing to remove: no %s, no %s, no sublayer in mod.usda" % (LAYER, BACKUP))
            return 0
        print("removed/undone:")
        for r in removed:
            print("  %s" % r)
        if args.dry_run:
            print("(dry run: nothing written)")
        print("All checks passed." if not args.dry_run else "")
        return 0

    entries = read_hashes(args.config, args.hash)
    if not entries:
        raise SystemExit("no texture hashes: put real 0x... lines in %s or pass --hash "
                         "(see docs/MIRRORS.md for how to read them in game)" % args.config)

    text = render(entries, args.roughness)
    validate(text, LAYER, need_mat=True)
    if args.show:
        print(text)
    old = open(mod, encoding="utf-8").read()
    new, changed, why = patch_mod_usda(old, args.position)
    validate(new, "mod.usda")

    if args.dry_run:
        print("would write %s (%d bytes, %d material override(s))" % (layer, len(text), len(entries)))
        print("would change mod.usda: %s" % why)
        return 0

    if not os.path.isfile(bak):
        shutil.copyfile(mod, bak)
        print("backup: %s" % bak)
    else:
        print("backup already exists (kept): %s" % bak)
    with open(layer, "w", encoding="utf-8") as f:
        f.write(text)
    if changed:
        with open(mod, "w", encoding="utf-8") as f:
            f.write(new)
    print("wrote %s: %d mirror material(s): %s" %
          (layer, len(entries), ", ".join(h for h, _ in entries)))
    for h, label in entries:
        print("  mat_%s  # %s" % (h, label))
    print("mod.usda: %s" % why)
    print("All checks passed.")
    return 0


def strip_sublayer(text):
    """Remove our sublayer entry (used by --remove when there is no backup)."""
    lines = text.splitlines(True)
    out, changed = [], False
    for line in lines:
        if SUB in line:
            changed = True
            if not line.rstrip().endswith(",") and out:
                # we were the last entry: the previous entry must not keep its comma
                prev = out[-1].rstrip()
                if prev.endswith(","):
                    out[-1] = prev[:-1] + ("\n" if out[-1].endswith("\n") else "")
            continue
        out.append(line)
    return "".join(out), changed, ("sublayer line removed" if changed else "no sublayer present")


if __name__ == "__main__":
    sys.exit(main())
